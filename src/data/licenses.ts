/**
 * Catálogo de licencias de software.
 *
 * Reglas:
 * - Solo productos que puedas distribuir legítimamente (con derechos del fabricante o distribuidor).
 * - NUNCA pongas claves, seriales ni credenciales en este archivo: todo lo que está aquí es público.
 * - `price: null` muestra “Precio a consultar”.
 * - `visible: false` oculta un producto sin borrarlo.
 * - `demo: true` = ejemplo de estructura; solo se ve en desarrollo y con etiqueta “Demostración”.
 */

export type Availability = 'disponible' | 'bajo-pedido' | 'fase-temprana' | 'en-desarrollo' | 'agotado';
export type ProductModel = 'commercial-license' | 'open-source-service';

export interface LicenseProduct {
  id: string;
  name: string;
  manufacturer: string;
  category: string;
  description: string;
  edition: string;
  platforms: string[];
  licenseType: string;
  duration: string;
  /** Número de dispositivos permitidos; null si no aplica. */
  devices: number | null;
  price: { amount: number; currency: 'PEN' | 'USD' } | null;
  availability: Availability;
  terms: string;
  refundPolicy: string;
  /** Distingue una licencia comercial de software gratuito con servicio de implementación. */
  productModel?: ProductModel;
  /** Texto comercial alternativo al precio calculado. */
  priceLabel?: string;
  /** Enlace oficial para verificar el proyecto y su estado. */
  officialUrl?: string;
  /** CTA alternativo para productos que no se venden como licencia. */
  ctaLabel?: string;
  /** Imagen oficial autorizada por el fabricante (opcional). */
  image?: { src: string; alt: string };
  visible: boolean;
  demo?: boolean;
}

